// conformance/INDEX.md maps each statement id of the specification to the tests
// that cite it and where they are declared. It is generated from the tests and
// the table; set UPDATE_CONFORMANCE=1 to rewrite it after either changes.
// `grep -rn MQTT-3.1.2-8 --include=*_test.go .` finds the same tests, because a
// TESTED row's tests must carry the id in dotted form in a comment or body.

const conformanceIndex = "conformance/INDEX.md"

// citingTests lists, sorted, every test that cites the row's id, by name or text.
func (r statementRow) citingTests(funcs map[string]testFunc) []string {
	var out []string
	for name, f := range funcs {
		if nameCites(name, r.id) {
			out = append(out, name)
			continue
		}
		for _, m := range statementIDText.FindAllString(f.text, -1) {
			if m == r.id {
				out = append(out, name)
				break
			}
		}
	}
	sort.Strings(out)
	return out
}

func indexDocument(rows []statementRow, funcs map[string]testFunc) string {
	var b strings.Builder
	b.WriteString("# Conformance index\n\n")
	b.WriteString("Generated by `conformance_index_test.go` from `mqtt5-statements.tsv` and the tests; do not edit.\n")
	b.WriteString("Regenerate with `UPDATE_CONFORMANCE=1 go test -run TestTheConformanceIndexIsCurrent .`\n")
	b.WriteString("Find a statement's tests with `grep -rn MQTT-3.1.2-8 --include='*_test.go' .`\n\n")
	b.WriteString("| Statement | Class | Tests (file:line) |\n|---|---|---|\n")
	for _, r := range rows {
		var cells []string
		for _, name := range r.citingTests(funcs) {
			cells = append(cells, fmt.Sprintf("`%s` (%s:%d)", name, funcs[name].file, funcs[name].line))
		}
		col := strings.Join(cells, "<br>")
		if len(cells) == 0 {
			col = "none: " + strings.ReplaceAll(r.evidence, "|", "/")
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.id, r.class, col)
	}
	return b.String()
}

func TestTheConformanceIndexIsCurrent(t *testing.T) {
	want := indexDocument(readStatements(t), testFuncs(t))
	have, _ := os.ReadFile(conformanceIndex)
	if string(have) == want {
		return
	}
	if ok, _ := strconv.ParseBool(os.Getenv("UPDATE_CONFORMANCE")); ok {
		require.NoError(t, os.WriteFile(conformanceIndex, []byte(want), 0o644))
		return
	}
	t.Fatalf("%s is stale; run UPDATE_CONFORMANCE=1 go test -run TestTheConformanceIndexIsCurrent .", conformanceIndex)
}

// A row that binds the Server must have a test in the index unless it says why
// none can exist; a row that is not tested says why.
func TestNoServerStatementIsWithoutATestOrAReason(t *testing.T) {
	funcs := testFuncs(t)
	for _, r := range readStatements(t) {
		tests := r.citingTests(funcs)
		switch r.class {
		case classTested:
			assert.NotEmpty(t, tests, "%s is TESTED and no test cites it", r.id)
			greppable := false
			for _, name := range tests {
				for _, m := range statementIDText.FindAllString(funcs[name].text, -1) {
					greppable = greppable || m == r.id
				}
			}
			assert.True(t, greppable, "%s: its tests cite it only by name; add the dotted id to a comment so grep finds it", r.id)
		case classNotApplic, classClientOnly:
			assert.NotEmpty(t, strings.TrimSpace(r.evidence), "%s: %s needs a reason", r.id, r.class)
		}
		if r.binds != "C" {
			assert.True(t, r.class == classTested || r.class == classNotApplic,
				"%s binds the Server and is %s: it needs a test or a reason it cannot be violated", r.id, r.class)
		}
	}
}
